package io.github.sammynashed.emran.data

import java.time.ZoneId

/**
 * A bundled city, identified by coordinates and an IANA time zone.
 *
 * [zoneId] replaced a `timezone: Double` field that stored a fixed UTC offset.
 * A fixed offset cannot describe a real place: 77 of the 164 cities in this list
 * observe daylight saving time, so for roughly half of every year their stored
 * offset was an hour wrong, and every prayer time and adhan alarm derived from it
 * was wrong with it. The zone id defers that question to the tz database, which
 * knows the rules for each date -- including Morocco's Ramadan shift and the
 * southern-hemisphere zones whose "summer" falls in January.
 */
data class LocationPreset(
    val name: String,
    val latitude: Double,
    val longitude: Double,
    val zoneId: String
) {
    /** Resolved zone, falling back to the device zone if the id is somehow unknown. */
    val zone: ZoneId get() = PrayerTimeCalculator.safeZone(zoneId)
}

