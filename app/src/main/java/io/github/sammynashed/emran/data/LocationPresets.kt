    fun findClosestPreset(latitude: Double, longitude: Double): LocationPreset {
        return list.minByOrNull { preset ->
            val dLat = preset.latitude - latitude
            val dLon = preset.longitude - longitude
            dLat * dLat + dLon * dLon
        } ?: list[0]
    }

    fun findClosestPreset(latitude: Double, longitude: Double, maxDistanceDegrees: Double): LocationPreset? {
        val closest = list.minByOrNull { preset ->
            val dLat = preset.latitude - latitude
            val dLon = preset.longitude - longitude
            dLat * dLat + dLon * dLon
        } ?: return null

        val dLat = closest.latitude - latitude
        val dLon = closest.longitude - longitude
        val distanceSq = dLat * dLat + dLon * dLon
        return if (distanceSq < maxDistanceDegrees * maxDistanceDegrees) closest else null
    }

